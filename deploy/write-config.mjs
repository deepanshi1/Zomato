// Vercel build step: point the static page at the Railway API.
import { writeFileSync } from "node:fs";

const base = (process.env.API_BASE_URL || "").trim().replace(/\/+$/, "");
if (!base) {
  console.error("API_BASE_URL is not set; set it to the Railway backend URL in the Vercel project.");
  process.exit(1);
}
writeFileSync(
  "app/static/config.js",
  `// Generated by deploy/write-config.mjs at build time.\nwindow.API_BASE = ${JSON.stringify(base)};\n`,
);
console.log(`config.js points at ${base}`);
